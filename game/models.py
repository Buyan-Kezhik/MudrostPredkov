from django.db import models
from django.contrib.auth.models import User
from django.utils import timezone


class Proverb(models.Model):
    """
    Модель 'Пословица' - хранит информацию о тувинских пословицах
    
    Поля:
    - text: полный текст пословицы с пропуском (обозначается как _____)
    - missing_word: слово, которое нужно угадать
    - hint: подсказка для игрока (необязательное поле)
    - created_at: дата добавления пословицы в базу
    
    Пример использования:
    Пословица: "Адакызы _____ деп, аразында чок деп"
    Пропущенное слово: "бар"
    """
    
    # Текстовое поле для хранения полного текста пословицы
    # help_text - подсказка, которая отображается в админ-панели
    text = models.TextField(
        "Текст пословицы",
        help_text="Полный текст тувинской пословицы с пропуском (обозначьте пропуск как _____)"
    )
    
    # Поле для хранения правильного ответа (пропущенного слова)
    # max_length=100 ограничивает максимальную длину слова
    missing_word = models.CharField(
        "Пропущенное слово",
        max_length=100,
        help_text="Слово, которое нужно вставить вместо пропуска"
    )
    
    # Необязательное поле для подсказки
    # blank=True, null=True разрешают оставить поле пустым
    hint = models.TextField(
        "Подсказка",
        blank=True,
        null=True,
        help_text="Необязательная подсказка для игроков"
    )
    
    # Автоматическое поле с датой создания записи
    # auto_now_add=True устанавливает дату при создании объекта
    created_at = models.DateTimeField(
        "Дата создания",
        auto_now_add=True,
        help_text="Дата и время добавления пословицы"
    )
    
    class Meta:
        """
        Мета-класс для настройки отображения модели в админ-панели
        """
        # Человеко-readable названия модели
        verbose_name = "Пословица"
        verbose_name_plural = "Пословицы"
        
        # Сортировка по дате создания (новые сверху)
        ordering = ['-created_at']
    
    def __str__(self):
        """
        Метод для строкового представления объекта
        Отображается в админ-панели и в отладочных целях
        """
        # Показываем первые 50 символов пословицы
        if len(self.text) > 50:
            return f"{self.text[:50]}..."
        return self.text


class GameSession(models.Model):
    """
    Модель 'Игровая сессия' - хранит информацию о каждой попытке игрока
    
    Описание:
    Каждая запись соответствует одной пословице, которую пытался 
    отгадать конкретный пользователь.
    
    Поля:
    - user: пользователь, который играет
    - proverb: пословица, которую нужно отгадать
    - attempts: количество попыток (максимум 3)
    - is_correct: правильный ли был дан ответ
    - completed_at: время завершения игры
    """
    
    # Связь с моделью пользователя Django
    # on_delete=models.CASCADE - при удалении пользователя удаляются все его сессии
    user = models.ForeignKey(
        User,
        on_delete=models.CASCADE,
        verbose_name="Пользователь",
        help_text="Игрок, который проходит квест"
    )
    
    # Связь с пословицей
    # Одна пословица может быть в многих сессиях (у разных игроков)
    proverb = models.ForeignKey(
        Proverb,
        on_delete=models.CASCADE,
        verbose_name="Пословица",
        help_text="Пословица для отгадывания"
    )
    
    # Счётчик попыток
    # default=0 устанавливает начальное значение
    attempts = models.IntegerField(
        "Попыток сделано",
        default=0,
        help_text="Количество попыток ответа (максимум 3)"
    )
    
    # Флаг правильного ответа
    # BooleanField хранит True/False
    is_correct = models.BooleanField(
        "Угадано",
        default=False,
        help_text="True если игрок дал правильный ответ"
    )
    
    # Время завершения сессии
    completed_at = models.DateTimeField(
        "Время завершения",
        auto_now_add=True,
        help_text="Дата и время завершения игры"
    )
    
    class Meta:
        """
        Мета-класс для настройки отображения
        """
        verbose_name = "Игровая сессия"
        verbose_name_plural = "Игровые сессии"
        
        # Сортировка по времени (последние сессии сверху)
        ordering = ['-completed_at']
    
    def __str__(self):
        """
        Строковое представление сессии
        """
        return f"{self.user.username} - {self.proverb.text[:30]}..."


class GameResult(models.Model):
    """
    Модель 'Результат игры' - агрегированная статистика игрока
    
    Описание:
    Используется для формирования таблицы лидеров (leaderboard).
    Хранит общую статистику по всем играм пользователя.
    
    Поля:
    - user: игрок
    - total_games: общее количество сыгранных игр
    - wins: количество побед (правильных ответов)
    - total_attempts: общее количество попыток
    - best_score: лучший результат (минимальное количество попыток)
    - last_played: последняя игра
    """
    
    # Связь с пользователем
    user = models.ForeignKey(
        User,
        on_delete=models.CASCADE,
        verbose_name="Пользователь",
        help_text="Игрок"
    )
    
    # Общее количество игр
    total_games = models.IntegerField(
        "Всего игр",
        default=0,
        help_text="Общее количество завершённых игр"
    )
    
    # Количество побед
    wins = models.IntegerField(
        "Побед",
        default=0,
        help_text="Количество игр с правильным ответом"
    )
    
    # Общее количество попыток
    total_attempts = models.IntegerField(
        "Всего попыток",
        default=0,
        help_text="Суммарное количество всех попыток"
    )
    
    # Лучший счёт (минимальное количество попыток для победы)
    best_score = models.IntegerField(
        "Лучший счёт",
        default=0,
        help_text="Минимальное количество попыток в победной игре"
    )
    
    # Дата последней игры
    # auto_now=True автоматически обновляется при каждом сохранении
    last_played = models.DateTimeField(
        "Последняя игра",
        auto_now=True,
        help_text="Дата и время последней игры"
    )
    
    class Meta:
        """
        Мета-класс для настройки таблицы лидеров
        """
        verbose_name = "Результат игры"
        verbose_name_plural = "Результаты игр"
        
        # Сортировка для лидерборда:
        # 1. Сначала по количеству побед (убывание)
        # 2. Затем по количеству попыток (возрастание - меньше лучше)
        ordering = ['-wins', 'total_attempts']
    
    def __str__(self):
        """
        Строковое представление результата
        """
        return f"{self.user.username} - Побед: {self.wins}/{self.total_games}"
    
    def calculate_win_percentage(self):
        """
        Метод для вычисления процента побед
        
        Возвращает:
        float: процент побед (0-100)
        """
        if self.total_games == 0:
            return 0.0
        return (self.wins / self.total_games) * 100