from django.contrib import admin
from django.urls import path, include

# Основные URL-паттерны проекта
urlpatterns = [
    # Админ-панель Django (для управления базой данных)
    path('admin/', admin.site.urls),
    
    # Подключение приложения game (основной сайт)
    # Все URL без префикса будут обрабатываться приложением game
    path('', include('game.urls')),
    
    # Подключение приложения accounts (регистрация/вход)
    # Все URL с префиксом /accounts/ будут обрабатываться приложением accounts
    path('accounts/', include('accounts.urls')),
]